"""
transcribe_videos.py — Transcribe all MP4/MOV/WEBM files using Whisper.

Usage:
    python3 tools/scripts/transcribe_videos.py [--model base] [--language nl]

Options:
    --model   Whisper model: tiny, base, small, medium, large (default: base)
    --language  Force language detection (default: auto-detect, "nl" for Dutch)
    --resume  Skip files that already have a transcription (default: True)

Reads all video files from VIDEOS_DIR, transcribes each one, and writes
plain-text transcriptions to OUTPUT_DIR.

Also writes a README.md index with topic categorisation.
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Optional

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

DRIVE_ROOT = Path(__file__).parents[3] / "SAAF Project Drive"
VIDEOS_DIR = DRIVE_ROOT / "Handy Resources - Photos and Videos"
OUTPUT_DIR = Path(__file__).parents[2] / "docs" / "transcriptions" / "videos"

VIDEO_EXTENSIONS = {".mp4", ".MP4", ".mov", ".MOV", ".webm", ".WEBM"}

# Topic categories for the index (keyword → category)
TOPIC_KEYWORDS = {
    "claude code": "Claude Code",
    "claude": "Claude Code",
    "skill": "Claude Code",
    "subagent": "Agent Orchestration",
    "sub agent": "Agent Orchestration",
    "agent": "Agent Orchestration",
    "orchestrat": "Agent Orchestration",
    "rag": "RAG & Context",
    "context engineering": "RAG & Context",
    "retrieval": "RAG & Context",
    "vector": "RAG & Context",
    "mcp": "MCP & Integrations",
    "n8n": "MCP & Integrations",
    "obsidian": "MCP & Integrations",
    "power bi": "MCP & Integrations",
    "security": "Security & Guardrails",
    "injection": "Security & Guardrails",
    "owasp": "Security & Guardrails",
    "vibe coding": "Security & Guardrails",
    "whisper": "Local Models",
    "ollama": "Local Models",
    "local": "Local Models",
    "deepseek": "Model Comparison",
    "openai": "Model Comparison",
    "gpt": "Model Comparison",
    "gemini": "Model Comparison",
    "cursor": "Model Comparison",
    "excel": "Productivity Tools",
    "copilot": "Productivity Tools",
    "notebooklm": "Productivity Tools",
}


def categorize(filename: str, transcript: str) -> str:
    text = (filename + " " + transcript).lower()
    for keyword, category in TOPIC_KEYWORDS.items():
        if keyword in text:
            return category
    return "General AI"


# ---------------------------------------------------------------------------
# Transcription
# ---------------------------------------------------------------------------

def transcribe_file(path: Path, model, language: Optional[str]) -> str:
    """Transcribe a single video file and return the text."""
    options = {}
    if language:
        options["language"] = language
    result = model.transcribe(str(path), **options)
    return result["text"].strip()


# ---------------------------------------------------------------------------
# Index writer
# ---------------------------------------------------------------------------

def write_index(entries: list[dict], output_dir: Path) -> None:
    """Write README.md index with topic categories."""
    by_category: dict[str, list[dict]] = {}
    for entry in entries:
        cat = entry["category"]
        by_category.setdefault(cat, []).append(entry)

    lines = [
        "# Video Transcription Index",
        "",
        "Auto-generated by `tools/scripts/transcribe_videos.py`.",
        "",
        f"**Total videos:** {len(entries)}",
        "",
        "---",
        "",
    ]

    for category in sorted(by_category.keys()):
        lines.append(f"## {category}")
        lines.append("")
        lines.append("| File | Transcription |")
        lines.append("|---|---|")
        for entry in sorted(by_category[category], key=lambda e: e["filename"]):
            slug = entry["slug"]
            name = entry["filename"]
            preview = entry["preview"]
            lines.append(f"| `{name}` | [{preview}...]({slug}.txt) |")
        lines.append("")

    (output_dir / "README.md").write_text("\n".join(lines), encoding="utf-8")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(description="Transcribe videos using Whisper")
    parser.add_argument("--model", default="base", help="Whisper model size (default: base)")
    parser.add_argument("--language", default=None, help="Force language (e.g. 'nl', 'en')")
    parser.add_argument("--no-resume", action="store_true", help="Re-transcribe already done files")
    args = parser.parse_args()

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    # Collect video files
    video_files = sorted(
        [f for f in VIDEOS_DIR.iterdir() if f.suffix in VIDEO_EXTENSIONS],
        key=lambda f: f.name,
    )

    if not video_files:
        print(f"No video files found in: {VIDEOS_DIR}")
        sys.exit(1)

    print(f"Found {len(video_files)} video files.")
    print(f"Loading Whisper model: {args.model} ...", flush=True)

    import whisper  # type: ignore
    from typing import Optional  # noqa
    model = whisper.load_model(args.model)
    print(f"Model loaded.")

    entries = []
    for i, video_path in enumerate(video_files, start=1):
        slug = re.sub(r"[^\w\-]", "_", video_path.stem)
        output_path = OUTPUT_DIR / f"{slug}.txt"

        if output_path.exists() and not args.no_resume:
            print(f"[{i}/{len(video_files)}] SKIP (exists): {video_path.name}")
            transcript = output_path.read_text(encoding="utf-8")
        else:
            print(f"[{i}/{len(video_files)}] Transcribing: {video_path.name} ...", end=" ", flush=True)
            try:
                transcript = transcribe_file(video_path, model, args.language)
                output_path.write_text(transcript, encoding="utf-8")
                words = len(transcript.split())
                print(f"{words} words")
            except Exception as exc:
                print(f"ERROR: {exc}")
                transcript = f"[Transcription failed: {exc}]"
                output_path.write_text(transcript, encoding="utf-8")

        category = categorize(video_path.name, transcript)
        preview = transcript[:80].replace("\n", " ") if transcript else "(empty)"
        entries.append({
            "filename": video_path.name,
            "slug": slug,
            "category": category,
            "preview": preview,
        })

    print("\nWriting index ...")
    write_index(entries, OUTPUT_DIR)
    print(f"Done. Output in: {OUTPUT_DIR}")


# Late import for the categorize function
import re
from typing import Optional

if __name__ == "__main__":
    main()
