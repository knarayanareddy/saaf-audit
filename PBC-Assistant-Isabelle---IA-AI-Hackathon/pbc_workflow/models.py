"""
Data models for the PBC Audit Workflow.
"""

from __future__ import annotations
from dataclasses import dataclass, field, asdict
from datetime import date
from typing import List, Optional
import json


# ── PBC item statuses ────────────────────────────────────────────────────────

PENDING   = "pending"
RECEIVED  = "received"
VALIDATED = "validated"
OVERDUE   = "overdue"


# ── Core data classes ─────────────────────────────────────────────────────────

@dataclass
class PBCItem:
    """A single document request in the PBC list."""
    id: str
    description: str
    deadline: str          # ISO date string: "YYYY-MM-DD"
    status: str = PENDING  # pending | received | validated | overdue


@dataclass
class AuditeeContact:
    name: str
    email: str
    organization: str


@dataclass
class ReceivedDocument:
    filename: str
    pbc_id: str            # claimed PBC ID (may be empty if unknown)


# ── Agent output containers ───────────────────────────────────────────────────

@dataclass
class PBCList:
    """Output of PBC_Creation_Agent."""
    audit_scope: str
    audit_period: str
    items: List[PBCItem] = field(default_factory=list)

    def to_json(self) -> str:
        return json.dumps(asdict(self), indent=2)

    @classmethod
    def from_dict(cls, d: dict) -> "PBCList":
        items = [PBCItem(**i) for i in d.get("items", [])]
        return cls(
            audit_scope=d["audit_scope"],
            audit_period=d["audit_period"],
            items=items,
        )


@dataclass
class DeliveryStatus:
    """Output of PBC_Distribution_Agent."""
    recipient_name: str
    recipient_email: str
    sent_at: str           # ISO datetime string
    email_subject: str
    email_body: str
    confirmed: bool = False


@dataclass
class ValidationResult:
    """Per-item result from Document_Validation_Agent."""
    pbc_id: str
    status: str            # received | validated | pending | overdue
    matched_file: Optional[str] = None
    notes: str = ""


@dataclass
class ValidationStatus:
    """Output of Document_Validation_Agent."""
    results: List[ValidationResult] = field(default_factory=list)

    def to_json(self) -> str:
        return json.dumps(
            [
                {
                    "pbc_id": r.pbc_id,
                    "status": r.status,
                    "matched_file": r.matched_file,
                    "notes": r.notes,
                }
                for r in self.results
            ],
            indent=2,
        )


@dataclass
class DashboardReport:
    """Output of Status_Dashboard_Agent."""
    total_items: int
    received_count: int
    validated_count: int
    pending_count: int
    overdue_count: int
    completion_percentage: float
    missing_items: List[str]       # list of PBC IDs still outstanding
    summary_text: str


@dataclass
class ReminderMessage:
    """A single reminder generated by Reminder_Agent."""
    pbc_id: str
    description: str
    days_overdue: int
    escalated: bool
    subject: str
    body: str


@dataclass
class ReminderLog:
    """Output of Reminder_Agent."""
    messages: List[ReminderMessage] = field(default_factory=list)
    activity_log: str = ""
